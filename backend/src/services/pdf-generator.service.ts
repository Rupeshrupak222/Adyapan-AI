/** Fallback PDF generator using pure PDFKit if Puppeteer fails */
function generateNotesPdfKitFallback(markdown: string, topic: string): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    try {
      const doc = new PDFDocument({ size: "A4", margin: 48 });
      const chunks: Buffer[] = [];
      doc.on("data", (chunk: Buffer) => chunks.push(chunk));
      doc.on("end", () => resolve(Buffer.concat(chunks)));
      doc.on("error", reject);

      // Top Banner
      doc.rect(0, 0, 595, 50).fill("#0F172A");
      doc.fillColor("#F59E0B").fontSize(16).font("Helvetica-Bold").text("Adyapan AI", 48, 16);
      doc.fillColor("#94A3B8").fontSize(9).font("Helvetica").text(`Study Notes · ${topic}`, 180, 20);
      
      doc.y = 70;

      // Title
      doc.fillColor("#0F172A").fontSize(18).font("Helvetica-Bold").text(topic);
      doc.moveDown(0.3);
      doc.strokeColor("#E2E8F0").lineWidth(1).moveTo(48, doc.y).lineTo(547, doc.y).stroke();
      doc.moveDown(0.6);

      // Markdown Content Parsing
      const textContent = typeof markdown === "string" ? markdown : String(markdown || "");
      const lines = textContent.split("\n");

      for (const line of lines) {
        const trimmed = line.trim();
        if (!trimmed) {
          doc.moveDown(0.2);
          continue;
        }

        if (trimmed.startsWith("# ")) {
          doc.moveDown(0.3);
          doc.fillColor("#0F172A").fontSize(15).font("Helvetica-Bold").text(trimmed.replace(/^#\s+/, ""));
          doc.moveDown(0.2);
        } else if (trimmed.startsWith("## ")) {
          doc.moveDown(0.2);
          doc.fillColor("#D97706").fontSize(13).font("Helvetica-Bold").text(trimmed.replace(/^##\s+/, ""));
          doc.moveDown(0.2);
        } else if (trimmed.startsWith("### ")) {
          doc.moveDown(0.2);
          doc.fillColor("#334155").fontSize(11).font("Helvetica-Bold").text(trimmed.replace(/^###\s+/, ""));
          doc.moveDown(0.15);
        } else if (trimmed.startsWith("- ") || trimmed.startsWith("* ")) {
          const itemText = trimmed.replace(/^[-*]\s+/, "").replace(/\*\*(.*?)\*\*/g, "$1");
          doc.fillColor("#1E293B").fontSize(9.5).font("Helvetica").text(`• ${itemText}`, { indent: 12 });
          doc.moveDown(0.1);
        } else if (trimmed.startsWith("> ")) {
          const calloutText = trimmed.replace(/^>\s*/, "").replace(/\*\*(.*?)\*\*/g, "$1");
          doc.fillColor("#B45309").fontSize(9.5).font("Helvetica-Oblique").text(`Note: ${calloutText}`, { indent: 14 });
          doc.moveDown(0.15);
        } else {
          const plainText = trimmed.replace(/\*\*(.*?)\*\*/g, "$1");
          doc.fillColor("#1E293B").fontSize(9.5).font("Helvetica").text(plainText);
          doc.moveDown(0.15);
        }
      }

      // Footer
      doc.moveDown(1);
      doc.fillColor("#94A3B8").fontSize(8).font("Helvetica").text(`Generated by Adyapan AI Engine · ${new Date().toLocaleDateString()}`, { align: "center" });

      doc.end();
    } catch (err) {
      reject(err);
    }
  });
}

/**
 * Generate a professional PDF from raw markdown notes.
 * Includes Adyapan AI header/footer, page numbers, and professional layout.
 */
export async function generateNotesPdf(
  markdown: string,
  topic: string,
  options?: NotesFormatOptions
): Promise<Buffer> {
  const htmlContent = formatNotesHtml(markdown, topic, options);
  const { headerTemplate, footerTemplate } = buildHeaderFooterTemplates(topic);

  let browser;
  try {
    browser = await puppeteer.launch({
      headless: true,
      args: [
        "--no-sandbox",
        "--disable-setuid-sandbox",
        "--disable-dev-shm-usage",
        "--disable-gpu",
        "--single-process",
        "--no-zygote",
      ],
    });

    const page = await browser.newPage();

    const cspMeta = '<meta http-equiv="Content-Security-Policy" content="default-src \'none\'; img-src https: data: blob:; style-src \'unsafe-inline\' https://fonts.googleapis.com; font-src https://fonts.gstatic.com data:;">';
    const hardenedHtml = htmlContent.replace("<head>", `<head>${cspMeta}`);

    await page.setContent(hardenedHtml, {
      waitUntil: "domcontentloaded",
      timeout: 20000,
    });

    const pdfBuffer = await page.pdf({
      format: "A4",
      printBackground: true,
      displayHeaderFooter: true,
      headerTemplate,
      footerTemplate,
      margin: {
        top: "18mm",
        bottom: "16mm",
        left: "0px",
        right: "0px",
      },
      preferCSSPageSize: false,
      timeout: 30000,
    });

    return Buffer.from(pdfBuffer);
  } catch (error: any) {
    console.warn(
      "[PDF Generator] Puppeteer failed, using PDFKit fallback:",
      error?.message || error
    );
    return generateNotesPdfKitFallback(markdown, topic);
  } finally {
    if (browser) {
      try {
        await browser.close();
      } catch {
        // Ignore close errors
      }
    }
  }
}

/**
 * Generate a PDF from pre-formatted HTML content.
 * Useful when the HTML has already been formatted by formatNotesHtml.
 */
export async function generatePdfFromHtml(
  htmlContent: string,
  topic: string
): Promise<Buffer> {
  const { headerTemplate, footerTemplate } = buildHeaderFooterTemplates(topic);

  let browser;
  try {
    browser = await puppeteer.launch({
      headless: true,
      args: [
        "--no-sandbox",
        "--disable-setuid-sandbox",
        "--disable-dev-shm-usage",
        "--disable-gpu",
        "--single-process",
        "--no-zygote",
      ],
    });

    const page = await browser.newPage();

    const cspMeta = '<meta http-equiv="Content-Security-Policy" content="default-src \'none\'; img-src https: data: blob:; style-src \'unsafe-inline\' https://fonts.googleapis.com; font-src https://fonts.gstatic.com data:;">';
    const hardenedHtml = htmlContent.replace("<head>", `<head>${cspMeta}`);

    await page.setContent(hardenedHtml, {
      waitUntil: "domcontentloaded",
      timeout: 20000,
    });

    const pdfBuffer = await page.pdf({
      format: "A4",
      printBackground: true,
      displayHeaderFooter: true,
      headerTemplate,
      footerTemplate,
      margin: {
        top: "18mm",
        bottom: "16mm",
        left: "0px",
        right: "0px",
      },
      preferCSSPageSize: false,
      timeout: 30000,
    });

    return Buffer.from(pdfBuffer);
  } catch (error: any) {
    console.warn(
      "[PDF Generator] Puppeteer failed in HTML mode, using PDFKit fallback:",
      error?.message || error
    );
    const plainMarkdown = htmlContent.replace(/<[^>]+>/g, "\n");
    return generateNotesPdfKitFallback(plainMarkdown, topic);
  } finally {
    if (browser) {
      try {
        await browser.close();
      } catch {
        // Ignore close errors
      }
    }
  }
}
