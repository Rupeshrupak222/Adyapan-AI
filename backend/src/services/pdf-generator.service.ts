import puppeteer from "puppeteer";
import fs from "fs";
import path from "path";
import PDFDocument from "pdfkit";
import { formatNotesHtml, NotesFormatOptions } from "./notes-formatter.service";

function escapeXml(text: string): string {
  return text
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&apos;");
}

let cachedLogoBase64: string | null = null;
function getLogoBase64(): string {
  if (cachedLogoBase64) return cachedLogoBase64;
  try {
    const cwd = process.cwd();
    const candidatePaths = [
      path.resolve(cwd, "frontend/public/assets/logo.png"),
      path.resolve(cwd, "../frontend/public/assets/logo.png"),
      path.resolve(cwd, "public/assets/logo.png"),
      path.resolve(__dirname, "../../../frontend/public/assets/logo.png"),
      path.resolve(__dirname, "../../frontend/public/assets/logo.png"),
      path.resolve(__dirname, "../../public/assets/logo.png"),
    ];
    for (const p of candidatePaths) {
      if (fs.existsSync(p)) {
        const fileBuf = fs.readFileSync(p);
        cachedLogoBase64 = `data:image/png;base64,${fileBuf.toString("base64")}`;
        return cachedLogoBase64;
      }
    }
  } catch (err) {
    console.warn("[PDF Generator] Could not load logo image for PDF header:", err);
  }
  return "";
}

